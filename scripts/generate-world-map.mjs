// Generates src/data/worldMap.ts from Natural Earth (via the world-atlas package).
// Run: node scripts/generate-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature, mesh } from "topojson-client";
import { geoEquirectangular, geoPath } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));
const W = 1000, TOP = 84, BOTTOM = -58;
const scale = W / (2 * Math.PI);
const y0 = (TOP * Math.PI) / 180 * scale;
const H = Math.round(((TOP - BOTTOM) * Math.PI) / 180 * scale);
const projection = geoEquirectangular().scale(scale).translate([W / 2, y0]).precision(0.1);
const path = geoPath(projection).digits ? geoPath(projection).digits(1) : geoPath(projection);

const countries = feature(topo, topo.objects.countries);
const land = { type: "FeatureCollection", features: countries.features.filter((f) => f.id !== "010") }; // drop Antarctica
const landPath = path(land);
const borders = path(mesh(topo, topo.objects.countries, (a, b) => a !== b));
const india = countries.features.find((f) => f.properties.name === "India");
const indiaPath = path(india);

const out = `// GENERATED by scripts/generate-world-map.mjs - do not edit by hand.
// Source: Natural Earth 1:110m admin-0 countries via the \`world-atlas\` package (public domain).
// Projection: equirectangular, longitude -180..180, latitude ${BOTTOM}..${TOP}.

export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};

/** Projects [longitude, latitude] to SVG viewBox coordinates (same transform used to draw the paths). */
export function project(lon: number, lat: number): [number, number] {
  const k = ${W} / 360;
  return [(lon + 180) * k, (${TOP} - lat) * k];
}

export const landPath = ${JSON.stringify(landPath)};
export const bordersPath = ${JSON.stringify(borders)};
export const indiaPath = ${JSON.stringify(indiaPath)};
`;
writeFileSync("src/data/worldMap.ts", out);
console.log("H", H, "bytes", out.length);
